"""`basemap.py`, against the two ways a regenerated basemap goes wrong quietly.

The module is generated by `scripts/extract_basemap.mjs` and never hand-edited,
so nothing here tests logic. It tests that the artifact in the tree still says
what its own header says it says.

A collapsed ring. Douglas-Peucker has no endpoint to anchor on when first equals
last: the baseline has zero length, every perpendicular distance computes as
zero, and the ring drops to two points. The script splits rings before
simplifying, and the symptom when it stops doing that is subtle, because rings
clipped open by the frame edge survive. The map keeps Norway and Ukraine and
loses France. The point count and the per-ring shape assertions below are what
catch that without anyone having to look at a picture.

An inflated artifact. Rerunning the script at a finer tolerance costs nothing at
the prompt and adds tens of thousands of coordinates that every worker process
then parses at import. The size bound turns that into a failing test rather than
a slow pipeline nobody traces back to a basemap.
"""

import ast
import math
import re
from pathlib import Path

from infrahub_demo_otn import basemap
from infrahub_demo_otn.units import microdeg_to_deg
from tests.unit.conftest import objects_of_kind

RINGS = [ring for rings in basemap.COUNTRIES.values() for ring in rings]


def _pop_coordinates() -> list[tuple[float, float]]:
    """The shipped PoPs as (lon, lat) degrees, read from `objects/`.

    The customer campus is excluded because the map does not draw it and so
    does not frame around it.
    """
    return [
        (microdeg_to_deg(int(site["longitude_microdeg"])), microdeg_to_deg(int(site["latitude_microdeg"])))
        for site in objects_of_kind("OtnSite")
        if site.get("site_type", "pop") == "pop"
    ]


MAX_BYTES = 100 * 1024
"""Generated at 0.02 degrees the module is about 89 KB. Halving the tolerance
roughly doubles it, so this bound is loose enough to survive a country being
added upstream and tight enough to reject a finer simplification."""

MIN_RING_POINTS = 4
"""Three corners and the implicit closing edge. A collapsed ring has two."""

MIN_RING_AREA_SQ_DEG = 0.006
"""`MIN_AREA` in the extraction script. Smaller rings are dropped there."""


def header() -> str:
    assert basemap.__doc__ is not None
    return basemap.__doc__


def claimed(pattern: str) -> tuple[float, ...]:
    """The numbers the module docstring claims, as floats in the order written."""
    match = re.search(pattern, header())
    assert match is not None, f"the header no longer states {pattern!r}"
    return tuple(float(group) for group in match.groups())


def shoelace_area(ring: list[tuple[float, float]]) -> float:
    """Twice the signed area, halved and made positive. The closing edge is implicit."""
    total = 0.0
    for index, (x0, y0) in enumerate(ring):
        x1, y1 = ring[(index + 1) % len(ring)]
        total += x0 * y1 - x1 * y0
    return abs(total) / 2


