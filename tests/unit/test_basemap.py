def test_the_module_stays_small_enough_to_import_cheaply() -> None:
    """E4. Every worker process parses these literals once.

    A finer tolerance is a one-word edit to the script and shows up nowhere else,
    so the bound is the thing that reports it.
    """
    size = Path(basemap.__file__).stat().st_size
    assert size <= MAX_BYTES, f"basemap.py is {size / 1024:.1f} KB, over the {MAX_BYTES / 1024:.0f} KB bound"


def test_the_module_imports_nothing_at_all() -> None:
    """Pure data. Nothing under `src/` may reach for the SDK, and this file needs no one."""
    tree = ast.parse(Path(basemap.__file__).read_text(encoding="utf-8"))
    assert not [node for node in ast.walk(tree) if isinstance(node, (ast.Import, ast.ImportFrom))]
