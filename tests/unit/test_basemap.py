def test_there_is_something_to_draw() -> None:
    assert basemap.COUNTRIES
    assert all(rings for rings in basemap.COUNTRIES.values())
    assert all(isinstance(name, str) and name for name in basemap.COUNTRIES)


def test_every_ring_closes() -> None:
    """Closed implicitly, by the renderer, not by a repeated final point.

    Both halves matter. A repeated point would draw a zero-length segment and
    double-count in the point total, and a ring of two points is the
    Douglas-Peucker collapse this file exists to catch.
    """
    for ring in RINGS:
        assert len(ring) >= MIN_RING_POINTS
        assert ring[0] != ring[-1]
        assert shoelace_area(ring) >= MIN_RING_AREA_SQ_DEG


def test_every_point_is_a_pair_of_finite_numbers() -> None:
    """The annotation says float and a few literals are written as int.

    `(20,39.71)` is what rounding to three decimals produces for a whole degree,
    and Python reads that first value as an int. Arithmetic does not care and
    neither does the renderer, so the check is numeric and finite, not float.
    """
    for ring in RINGS:
        for point in ring:
            assert isinstance(point, tuple)
            assert len(point) == 2
            lon, lat = point
            assert isinstance(lon, (int, float)) and math.isfinite(lon)
            assert isinstance(lat, (int, float)) and math.isfinite(lat)


def test_every_point_lies_inside_the_declared_frame() -> None:
    """FR-013. The data is clipped, so nothing may sit outside the frame it names.

    A point beyond the frame is a point the renderer draws over the panel or off
    the canvas, and rounding the clipped coordinates to three decimals is the way
    it would happen.
    """
    lon0, lon1, lat0, lat1 = basemap.FRAME
    for ring in RINGS:
        for lon, lat in ring:
            assert lon0 <= lon <= lon1
            assert lat0 <= lat <= lat1


def test_the_frame_is_wider_than_it_is_tall_and_covers_western_europe() -> None:
    """Transposing the frame tuple is the cheap mistake, and it still parses."""
    lon0, lon1, lat0, lat1 = basemap.FRAME
    assert lon0 < lon1
    assert lat0 < lat1
    # Madrid and Warsaw are the east and west extremes of the fourteen PoPs, and
    # Madrid and Copenhagen the north and south. The clip clears all four.
    assert lon0 <= -3.71 and lon1 >= 21.02
    assert lat0 <= 40.41 and lat1 >= 55.68


def test_the_clip_contains_the_frame_the_map_actually_draws() -> None:
    """The bug this exists for: coastlines that stop inside the drawing area.

    The drawn frame is not the bounding box of the sites. `Frame.fit` grows the
    short axis to the canvas aspect, so the fourteen PoPs spanning lon
    -3.7 to 21.0 are drawn inside a frame reaching lon 26.7. A clip that stops
    at 25.5 satisfies every other test in this file and still puts a straight
    vertical cut through Ukraine and the Baltic, with sea drawn where land is.

    Asserted against the real site coordinates and the real canvas, because the
    two numbers that have to agree live in different files and nothing else
    compares them.
    """
    from infrahub_demo_otn import mapchrome
    from infrahub_demo_otn.cartography import Frame

    sites = _pop_coordinates()
    assert len(sites) == 14, "the fixture stopped reading the shipped PoPs"

    # The canvas belongs to `mapchrome.py`, which is the module both maps fit
    # their frame with. Reading it off either renderer would pass on a copy.
    frame = Frame.fit(
        sites,
        width=mapchrome.CANVAS_WIDTH,
        height=mapchrome.CANVAS_HEIGHT,
        pad_left=mapchrome.PAD_LEFT,
        pad_right=mapchrome.PAD_RIGHT,
        pad_top=mapchrome.PAD_TOP,
        pad_bottom=mapchrome.PAD_BOTTOM,
    )
    lon_min = math.degrees(frame.xmin)
    lon_max = math.degrees(frame.xmax)
    lat_min = math.degrees(2 * math.atan(math.exp(frame.ymin)) - math.pi / 2)
    lat_max = math.degrees(2 * math.atan(math.exp(frame.ymax)) - math.pi / 2)

    lon0, lon1, lat0, lat1 = basemap.FRAME
    assert lon0 <= lon_min, f"the map draws west to {lon_min:.2f} and the coastlines stop at {lon0}"
    assert lon1 >= lon_max, f"the map draws east to {lon_max:.2f} and the coastlines stop at {lon1}"
    assert lat0 <= lat_min, f"the map draws south to {lat_min:.2f} and the coastlines stop at {lat0}"
    assert lat1 >= lat_max, f"the map draws north to {lat_max:.2f} and the coastlines stop at {lat1}"


