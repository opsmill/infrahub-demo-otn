def test_the_header_names_its_source_and_its_licence() -> None:
    """FR-013. The data is redistributed, so the release and the licence ship with it."""
    text = header()
    assert "GENERATED by scripts/extract_basemap.mjs" in text
    assert "Natural Earth 1:50m" in text
    assert "world-atlas 2.0.2" in text
    assert "public domain" in text


def test_the_counts_in_the_header_match_the_data() -> None:
    """A regeneration that moves one without the other fails here.

    The header is the only human-readable record of what the script produced, so
    a stale count is a lie about the artifact and about which tolerance made it.
    """
    countries, rings, points = claimed(r"Holds (\d+) countries, (\d+) rings, (\d+) points")
    assert len(basemap.COUNTRIES) == countries
    assert len(RINGS) == rings
    assert sum(len(ring) for ring in RINGS) == points


def test_the_clip_frame_in_the_header_matches_the_frame_constant() -> None:
    numbers = claimed(r"Clipped to lon (-?[\d.]+)\.\.(-?[\d.]+) and lat (-?[\d.]+)\.\.(-?[\d.]+)")
    assert numbers == tuple(float(value) for value in basemap.FRAME)


def test_the_header_states_the_tolerance_the_data_was_simplified_at() -> None:
    (tolerance,) = claimed(r"simplified to ([\d.]+) degrees")
    assert tolerance == 0.02


